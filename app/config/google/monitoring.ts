import type {
  GcpAlertPolicyDefinition,
  GcpLogMetricDefinition,
} from "../../constructs/observability/googlecloudmonitoring";
import { alertEmails } from "../notifications";
import { LOCATION } from "./common";

/** Notification target: one email notification channel per address. */
export interface GoogleNotificationTargetConfig {
  /** Logical key referenced from alertPolicies[].notify */
  key: string;
  /** Channel display name prefix. Default: <PROJECT_NAME>-google-alerts-<key> */
  name?: string;
  emails: string[];
}

/** Alert policy. `notify` lists notificationTargets keys. */
export type GoogleAlertPolicyConfig = Omit<
  GcpAlertPolicyDefinition,
  "notificationChannels"
> & {
  notify?: string[];
  /**
   * Load balancer name in cloudloadbalancing.ts: the policy is created only
   * when that load balancer is built
   */
  loadBalancer?: string;
};

/**
 * Alerting configuration (created only when `clouds.google.features.alerting`
 * is enabled in commonsettings.ts).
 */
export const googleAlertingConfig: {
  notificationTargets: GoogleNotificationTargetConfig[];
  /** Log-based metrics usable from alertPolicies (metric type "logging.googleapis.com/user/<name>") */
  logMetrics: GcpLogMetricDefinition[];
  alertPolicies: GoogleAlertPolicyConfig[];
} = {
  notificationTargets: [{ key: "ops", emails: alertEmails }],
  logMetrics: [
    // Errors the API writes to its log (e.g. "Readiness check failed")
    {
      name: "api-errors",
      filter:
        'resource.type="cloud_run_revision" AND ' +
        'resource.labels.service_name="web-service-with-lb" AND textPayload:"failed"',
    },
    // The journal pruning job (Cloud Run job, apicontainer.ts journalPrune)
    {
      name: "journal-prune-failed",
      filter: 'resource.type="cloud_run_job" AND textPayload:"Journal pruning failed"',
    },
  ],
  alertPolicies: [
    ...[
      { name: "api-errors", resourceType: "cloud_run_revision" },
      { name: "journal-prune-failed", resourceType: "cloud_run_job" },
    ].map(({ name, resourceType }) => ({
      displayName: name,
      combiner: "OR" as const,
      conditionFilter:
        `metric.type="logging.googleapis.com/user/${name}" AND ` +
        `resource.type="${resourceType}"`,
      aggregation: { alignmentPeriod: "300s", perSeriesAligner: "ALIGN_SUM" },
      duration: "0s",
      comparison: "COMPARISON_GT" as const,
      thresholdValue: 0,
      notify: ["ops"],
    })),
    // 5xx of the API's load balancer (generated by it or returned by the
    // API). One per load balancer; only the built one gets it.
    ...[
      { lb: "run-regional-http-lb", forwardingRule: "run-regional-http-lb-http-fw" },
      { lb: "run-regional-https-lb", forwardingRule: "run-regional-https-lb-https-fw" },
    ].map(({ lb, forwardingRule }) => ({
      displayName: `${lb}-5xx`,
      loadBalancer: lb,
      combiner: "OR" as const,
      conditionFilter:
        'metric.type="loadbalancing.googleapis.com/https/external/regional/request_count" AND ' +
        'resource.type="http_external_regional_lb_rule" AND ' +
        `resource.labels.forwarding_rule_name="${forwardingRule}" AND ` +
        "metric.labels.response_code_class=500",
      aggregation: {
        alignmentPeriod: "300s",
        perSeriesAligner: "ALIGN_SUM",
        crossSeriesReducer: "REDUCE_SUM",
      },
      duration: "0s",
      // Threshold conditions support only GT and LT: more than 9 = 10 or more
      comparison: "COMPARISON_GT" as const,
      thresholdValue: 9,
      notify: ["ops"],
    })),
  ],
};

/**
 * Log archive to Cloud Storage (created only when
 * `clouds.google.features.logArchive` is enabled in commonsettings.ts).
 *
 * A log sink writes the logs of the Cloud Run services to the bucket in
 * hourly batches. The sink is independent of the _Default exclusions
 * (cloudlogging.ts), so services with `logs: false` are archived too.
 *
 * deleteOnDestroy: true deletes the bucket and the archived logs on destroy.
 * false keeps them, but destroy then fails while the bucket is not empty
 * (remove the bucket from the state before destroying to keep it).
 */
export const googleLogArchiveConfig: {
  deleteOnDestroy: boolean;
  bucket: {
    /** Required (globally unique) when logArchive is enabled */
    name?: string;
    location: string;
    lifecycle?: { toArchiveClassDays?: number; deleteDays?: number };
  };
  /** Default: <PROJECT_NAME>-google-log-archive */
  sinkName?: string;
  /** Cloud Run services to archive. Omitted: every built service */
  cloudRunServices?: string[];
  /** Logging query used instead of the one built from cloudRunServices */
  filter?: string;
  labels?: { [key: string]: string };
} = {
  deleteOnDestroy: true,
  bucket: {
    name: undefined,
    location: LOCATION,
    lifecycle: { toArchiveClassDays: 30, deleteDays: 365 },
  },
  labels: { component: "log-archive", managed_by: "cdktn" },
};
