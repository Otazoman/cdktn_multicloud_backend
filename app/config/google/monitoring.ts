import type {
  GcpAlertPolicyDefinition,
  GcpLogMetricDefinition,
} from "../../constructs/observability/googlecloudmonitoring";
import { alertEmails } from "../notifications";
import { LOCATION } from "./common";

/** Notification target: one email notification channel per address. */
export interface GoogleNotificationTargetConfig {
  /** Logical key referenced from alertPolicies[].notify */
  key: string;
  /** Channel display name prefix. Default: <PROJECT_NAME>-google-alerts-<key> */
  name?: string;
  emails: string[];
}

/** Alert policy. `notify` lists notificationTargets keys. */
export type GoogleAlertPolicyConfig = Omit<
  GcpAlertPolicyDefinition,
  "notificationChannels"
> & {
  notify?: string[];
  /**
   * Load balancer name in cloudloadbalancing.ts: the policy is created only
   * when that load balancer is built
   */
  loadBalancer?: string;
  /** Created only when the cicd feature is enabled (build results) */
  cicd?: boolean;
  /** false: the policy is not created. Default: true */
  enabled?: boolean;
};

/**
 * Uptime check of the API from the internet: one uptime check of /readyz
 * per built load balancer (its FQDN with the dns feature, else its IP), and
 * an alert policy on it. Created from build stage 3 (config/buildstage.ts):
 * before, the placeholder image does not answer /readyz.
 */
export interface GoogleUptimeCheckConfig {
  /** false: no uptime checks. Default: true */
  enabled: boolean;
  /** "60s", "300s", "600s" or "900s" */
  period: string;
  /** 1 to 60 seconds */
  timeout: string;
  /** Checker regions (at least 3 locations). Omitted: all */
  selectedRegions?: string[];
  /** The policy fires when more than this many checker regions fail ... */
  failedRegionsAbove: number;
  /** ... for this long (e.g. "120s") */
  duration: string;
  /** notificationTargets keys */
  notify: string[];
}

